SET DEFINE OFF;

-- Clean up existing tables and sequences if they exist
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE project_members CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE join_requests CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE projects CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE students CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- ----------------------------------------------------------------------------
-- 1. Table: STUDENTS
-- ----------------------------------------------------------------------------
CREATE TABLE students (
    student_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR2(100) NOT NULL,
    email          VARCHAR2(120) NOT NULL CONSTRAINT uq_student_email UNIQUE,
    department     VARCHAR2(100) NOT NULL,
    year_of_study  VARCHAR2(30)  NOT NULL,
    skills         VARCHAR2(500),
    bio            VARCHAR2(1000),
    avatar_url     VARCHAR2(255),
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 2. Table: PROJECTS
-- ----------------------------------------------------------------------------
CREATE TABLE projects (
    project_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR2(200) NOT NULL,
    description     VARCHAR2(3000) NOT NULL,
    category        VARCHAR2(100) NOT NULL,
    technologies    VARCHAR2(500) NOT NULL,
    owner_id        NUMBER NOT NULL,
    team_size       NUMBER DEFAULT 4 NOT NULL,
    required_skills VARCHAR2(500) NOT NULL,
    status          VARCHAR2(30) DEFAULT 'Open' NOT NULL,
    github_url      VARCHAR2(255),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_project_owner FOREIGN KEY (owner_id) 
        REFERENCES students(student_id) ON DELETE CASCADE,
    CONSTRAINT chk_project_status CHECK (status IN ('Open', 'In Progress', 'Completed')),
    CONSTRAINT chk_team_size CHECK (team_size >= 1 AND team_size <= 20)
);

-- ----------------------------------------------------------------------------
-- 3. Table: PROJECT_MEMBERS
-- ----------------------------------------------------------------------------
CREATE TABLE project_members (
    member_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   NUMBER NOT NULL,
    student_id   NUMBER NOT NULL,
    role         VARCHAR2(50) DEFAULT 'Contributor' NOT NULL,
    joined_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_member_project FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT fk_member_student FOREIGN KEY (student_id) 
        REFERENCES students(student_id) ON DELETE CASCADE,
    CONSTRAINT uq_project_member UNIQUE (project_id, student_id)
);

-- ----------------------------------------------------------------------------
-- 4. Table: JOIN_REQUESTS
-- ----------------------------------------------------------------------------
CREATE TABLE join_requests (
    request_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    NUMBER NOT NULL,
    student_id    NUMBER NOT NULL,
    message       VARCHAR2(1000),
    status        VARCHAR2(30) DEFAULT 'Pending' NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    responded_at  TIMESTAMP,
    CONSTRAINT fk_request_project FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT fk_request_student FOREIGN KEY (student_id) 
        REFERENCES students(student_id) ON DELETE CASCADE,
    CONSTRAINT chk_request_status CHECK (status IN ('Pending', 'Accepted', 'Rejected')),
    CONSTRAINT uq_join_request UNIQUE (project_id, student_id)
);

-- ----------------------------------------------------------------------------
-- Indexes for Performance
-- ----------------------------------------------------------------------------
CREATE INDEX idx_proj_owner ON projects(owner_id);
CREATE INDEX idx_proj_category ON projects(category);
CREATE INDEX idx_proj_status ON projects(status);
CREATE INDEX idx_req_project ON join_requests(project_id);
CREATE INDEX idx_req_student ON join_requests(student_id);
CREATE INDEX idx_req_status ON join_requests(status);
CREATE INDEX idx_member_proj ON project_members(project_id);
CREATE INDEX idx_member_stud ON project_members(student_id);

COMMIT;
